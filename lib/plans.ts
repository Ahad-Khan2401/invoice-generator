export interface PlanLimits {
  /** Max saved documents in the dashboard (Infinity = unlimited). */
  savedDocuments: number;
  /** Max saved clients in the client directory. */
  clients: number;
  /** Max saved business profiles. */
  businessProfiles: number;
  /** Premium PDF templates (Minimal, Bold). */
  premiumTemplates: boolean;
  /** Reversed/Centered header designs and notes-first section order. */
  advancedLayouts: boolean;
  /** 12 premium colour themes. */
  premiumColours: boolean;
  /** Remove the "Generated by pdfbillbuilder.com" footer line. */
  whiteLabel: boolean;
  /** No ads anywhere on the site. */
  adFree: boolean;
  /** CSV export of the invoice history. */
  csvExport: boolean;
  /** Bulk / recurring features (Business only, scaffolded). */
  bulkGeneration: boolean;
  teamSeats: number;
}

export interface PlanDef {
  key: PlanKey;
  name: string;
  tagline: string;
  /** Monthly headline price string, e.g. "$5.99". Empty for free. */
  priceMonthly: string;
  /** Optional yearly price string, shown only when checkoutYearly is set. */
  priceYearly?: string;
  /** Hosted checkout URLs (Lemon Squeezy). Undefined => not purchasable. */
  checkoutMonthly?: string;
  checkoutYearly?: string;
  /** Hide the plan from pricing UI entirely until enabled. */
  enabled: boolean;
  limits: PlanLimits;
  highlights: string[];
}

