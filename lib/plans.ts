/* ───────────────────────────────────────────────────────────────
   Plans, prices, limits and entitlements — single source of truth.

   The Pro price shown everywhere MUST match the live Lemon Squeezy
   product ($5.99 / month, store 397470). The yearly Pro variant and
   the Business plan are OPTIONAL: they only appear once a checkout
   URL is provided via config/env, so the UI can never advertise a
   price that cannot actually be bought.

   Prices are test hypotheses, not validated market prices.
──────────────────────────────────────────────────────────────── */

