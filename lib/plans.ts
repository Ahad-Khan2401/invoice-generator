export const PLAN_ORDER: PlanKey[] = ["free", "pro", "business"];

export function planFor(key: string | null | undefined): PlanDef {
  return (key && key in PLANS ? PLANS[key as PlanKey] : PLANS.free);
}

/** Convenience: any paid plan. */
export function isPaid(key: PlanKey): boolean {
  return key !== "free";
}

/** Human price label used in buttons/modals: "$5.99 / month". */
export function priceLabel(plan: PlanDef, period: "month" | "year" = "month"): string {
  if (period === "year" && plan.priceYearly) return `${plan.priceYearly} / year`;
  return `${plan.priceMonthly} / month`;
}

/** Numeric monthly value for analytics (never sent with user data). */
export function priceValue(plan: PlanDef): number {
  const n = parseFloat(plan.priceMonthly.replace(/[^0-9.]/g, ""));
  return isFinite(n) ? n : 0;
}

/** Lemon Squeezy variant → plan mapping (optional, via env, comma-separated IDs). */
function idList(v: string | undefined): Set<string> {
  return new Set((v ?? "").split(",").map((s) => s.trim()).filter(Boolean));
}
const BUSINESS_VARIANTS = idList(process.env.LS_BUSINESS_VARIANT_IDS);

export function planFromVariant(variantId: string | number | null | undefined): PlanKey {
  if (variantId != null && BUSINESS_VARIANTS.has(String(variantId))) return "business";
  return "pro";
}

/** Subscription statuses that grant access. `past_due` keeps access during
    Lemon Squeezy's dunning window so a failed card doesn't instantly lock
    someone out; `unpaid`/`expired`/`cancelled`(after ends_at) do not. */
export const ACTIVE_STATUSES = new Set(["active", "on_trial", "past_due", "paused_grace"]);

export function statusGrantsAccess(status: string | null | undefined, endsAt?: string | Date | null): boolean {
  if (!status) return false;
  if (ACTIVE_STATUSES.has(status)) return true;
  // A cancelled subscription keeps access until the paid period ends.
  if (status === "cancelled" && endsAt) {
    const t = new Date(endsAt).getTime();
    return isFinite(t) && t > Date.now();
  }
  return false;
}
